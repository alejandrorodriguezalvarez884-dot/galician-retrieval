"""Holm over family E: the reviewed DOG 2025 test set.

Family E is the six comparisons fixed in human-test/analysis-plan.md before scoring, strict MRR,
paired bootstrap over questions from eval_human.py's results.json. A p of 0 (no resample on
the other side of zero) enters as 2/(B+1), as in holm.md.

Sensitivity: families A and E together. Family A's raw values are read from the "Raw used"
column of holm-results.md (written by analysis/holm.py); "<0.001" and "<=x" enter as their
bound (0.001 or x), which keeps the adjusted values conservative.

    python analysis/holm.py --out holm-results.md
    python analysis/holm_e.py --results results/human-test/reviewed.json --out holm-results-E.md
"""
import argparse
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from holm import holm  # noqa: E402
FAMILY_E = [("mix", "bm25"), ("mix", "bge-m3"), ("mix", "nos"),
            ("run5", "bm25"), ("run5", "bge-m3"), ("run5", "nos")]
CONTEXT = [("mix", "run5"), ("nos", "bm25")]
NAMES = {"mix": "mix 0.9", "run5": "run 5", "bm25": "BM25", "bge-m3": "bge-m3", "nos": "Nos pipeline"}


def family_a(path: Path) -> list[tuple[str, float]]:
    text = path.read_text(encoding="utf-8")
    section = text.split("## A.", 1)[1].split("\n## ", 1)[0]
    rows = []
    for line in section.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 7 or cells[0] in ("Comparison (A - B)", "---"):
            continue
        raw = cells[3]
        value = float(re.sub(r"[^0-9.]", "", raw))
        rows.append((cells[0], value))
    return rows


def fmt(p: float) -> str:
    return "<0.001" if p < 0.001 else f"{p:.3f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", required=True, type=Path)
    ap.add_argument("--holm-results", type=Path, default=Path("holm-results.md"))
    ap.add_argument("--out", required=True, type=Path)
    args = ap.parse_args()

    report = json.loads(args.results.read_text(encoding="utf-8"))
    boot = {(b["a"], b["b"]): b for b in report["bootstrap"] if b["metric"] == "mrr"}
    samples = report["info"].get("samples", 10000)
    floor = 2 / (samples + 1)

    rows = []
    for a, b in FAMILY_E:
        line = boot[(a, b)]
        p = line["p_two_sided"]
        rows.append({"name": f"{NAMES[a]} - {NAMES[b]}", "diff": line["diff"], "ci": line["ci95"],
                     "raw": p, "used": max(p, floor), "doc_ci": line["by_document"]["ci95"],
                     "doc_p": line["by_document"]["p_two_sided"]})
    adj_e, _ = holm([r["used"] for r in rows], [False] * len(rows))

    a_rows = family_a(args.holm_results)
    combined = [r["used"] for r in rows] + [v for _, v in a_rows]
    adj_ae, _ = holm(combined, [False] * len(combined))

    out = ["# Holm over family E: reviewed DOG 2025 test set (generated by holm_e.py)", "",
           f"Source: `{args.results}`. Strict MRR, paired bootstrap over questions ({samples:,} resamples). "
           f"Family E fixed in `human-test/analysis-plan.md` before scoring. A p of 0 enters as {floor:.4f}.", "",
           f"m = {len(rows)}; sensitivity A + E: m = {len(combined)} (family A raw values from `holm-results.md`, bounds as upper values).", "",
           "| Comparison (A - B) | Diff | 95 % interval | Raw p | Holm (E) | Holm (A + E) | By-document interval, p |",
           "|---|---|---|---|---|---|---|"]
    for r, pe, pae in zip(rows, adj_e, adj_ae[: len(rows)]):
        out.append(f"| {r['name']} | {r['diff']:+.3f} | [{r['ci'][0]:+.3f}, {r['ci'][1]:+.3f}] | {fmt(r['raw'])} | "
                   f"{fmt(pe)} | {fmt(pae)} | [{r['doc_ci'][0]:+.3f}, {r['doc_ci'][1]:+.3f}], {fmt(r['doc_p'])} |")
    out += ["", "Context only (no claim, raw values):", ""]
    for a, b in CONTEXT:
        line = boot.get((a, b))
        if line:
            out.append(f"- {NAMES[a]} - {NAMES[b]}: {line['diff']:+.3f} [{line['ci95'][0]:+.3f}, {line['ci95'][1]:+.3f}], p {fmt(line['p_two_sided'])}")
    out += ["", "Family A in the A + E check (adjusted p):", ""]
    for (name, raw), p in zip(a_rows, adj_ae[len(rows):]):
        out.append(f"- {name}: raw {raw:g}, Holm (A + E) {fmt(p)}")
    args.out.write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out[:8 + len(rows)]))


if __name__ == "__main__":
    main()
